//! What each RPC handler's own decode makes of a payload, isolated from the handler: the contract type it deserializes into
//! (or the function that does it), run over the same payloads as the gate. `rpc_decode_tests.rs` measures each against the
//! original's decoding, with and without the gate in front, and compares the values the handler would act on.
//! A decoder answers with the handler's value, re-serialized, so two payloads that make the handler act alike compare equal.
use serde_json::Value;
use t3_contracts::*;

pub(crate) type Decoded = Result<Value, String>;

fn typed<T: serde::de::DeserializeOwned + serde::Serialize>(payload: &Value) -> Decoded {
    let value: T = serde_json::from_value(payload.clone()).map_err(|error| error.to_string())?;
    serde_json::to_value(value).map_err(|error| error.to_string())
}
fn nothing(payload: &Value) -> Decoded {
    Ok(payload.clone())
}
fn non_null(payload: &Value) -> Decoded {
    if payload.is_null() { Err("Expected a non-null value.".into()) } else { Ok(payload.clone()) }
}
fn failed(error: Value) -> String {
    error["message"].as_str().map(str::to_owned).unwrap_or_else(|| error.to_string())
}

macro_rules! table {
    ($method:expr, { $($name:literal => $decoder:expr),* $(,)? }) => {
        match $method { $($name => Some($decoder as fn(&Value) -> Decoded),)* _ => None }
    };
}

