// Writes crates/server/src/pull_request_queries.rs from the original GraphQL documents, so the
// Rust port sends exactly what gitHubPullRequestJson.ts sends. Run: node tools/generate_pull_request_queries.mjs
import { writeFileSync, renameSync } from "node:fs";
import * as J from "../../apps/server/src/pullRequest/gitHubPullRequestJson.ts";
const statics = [
  "ACTOR_AVATARS_GRAPHQL_QUERY",
  "PULL_REQUEST_PREVIEW_GRAPHQL_QUERY",
  "PULL_REQUEST_ACTIVITY_GRAPHQL_QUERY",
  "REVIEW_THREADS_GRAPHQL_QUERY",
  "REVIEW_THREAD_COMMENTS_GRAPHQL_QUERY",
  "REVIEW_THREAD_REPLY_GRAPHQL_MUTATION",
  "PULL_REQUEST_NODE_ID_GRAPHQL_QUERY",
  "REACTION_SUBJECT_PULL_REQUEST_GRAPHQL_QUERY",
  "ADD_REACTION_GRAPHQL_MUTATION",
  "REMOVE_REACTION_GRAPHQL_MUTATION",
  "RESOLVE_REVIEW_THREAD_GRAPHQL_MUTATION",
  "UNRESOLVE_REVIEW_THREAD_GRAPHQL_MUTATION",
  "UPDATE_PULL_REQUEST_GRAPHQL_MUTATION",
  "REVERT_PULL_REQUEST_GRAPHQL_MUTATION",
  "UPDATE_ISSUE_COMMENT_GRAPHQL_MUTATION",
  "UPDATE_REVIEW_COMMENT_GRAPHQL_MUTATION",
  "REVIEW_DISMISSALS_GRAPHQL_QUERY",
  "PULL_REQUEST_HEADS_GRAPHQL_QUERY",
  "REVIEWER_CANDIDATES_GRAPHQL_QUERY",
  "LABEL_CANDIDATES_GRAPHQL_QUERY",
  "VIEWER_PERMISSIONS_GRAPHQL_QUERY",
  "PULL_REQUEST_FILES_VIEWED_GRAPHQL_QUERY",
];
const lit = (text) => {
  let hashes = "#";
  while (text.includes('"' + hashes)) hashes += "#";
  return `r${hashes}"${text}"${hashes}`;
};
let out =
  "//! GENERATED by tools/generate_pull_request_queries.mjs from the original GraphQL documents. Do not edit.\n";
for (const name of statics) {
  if (typeof J[name] !== "string") throw new Error(`missing ${name}`);
  out += `pub const ${name}: &str = ${lit(J[name])};\n`;
}
out += `\n/// Core read, written for github.com (asks which checks the base branch requires) or any other host.\npub fn core_query(github_com: bool) -> &'static str {\n    if github_com { CORE_GITHUB_COM } else { CORE_OTHER }\n}\n`;
out += `pub const CORE_GITHUB_COM: &str = ${lit(J.pullRequestCoreGraphQlQuery("github.com"))};\npub const CORE_OTHER: &str = ${lit(J.pullRequestCoreGraphQlQuery("ghe.example.com"))};\n`;
out += `\npub fn check_contexts_query(github_com: bool) -> &'static str {\n    if github_com { CHECK_CONTEXTS_GITHUB_COM } else { CHECK_CONTEXTS_OTHER }\n}\n`;
out += `pub const CHECK_CONTEXTS_GITHUB_COM: &str = ${lit(J.pullRequestCheckContextsGraphQlQuery("github.com"))};\npub const CHECK_CONTEXTS_OTHER: &str = ${lit(J.pullRequestCheckContextsGraphQlQuery("ghe.example.com"))};\n`;
out += `\npub const SUMMARY_SINGLE: &str = ${lit(J.pullRequestSummaryGraphQlQuery(false))};\npub const SUMMARY_SINGLE_WITH_STACKS: &str = ${lit(J.pullRequestSummaryGraphQlQuery(true))};\n`;
// The fields one summary reads, as the aliased batch document writes them around each lookup.
const selection = (stacks) => {
  const sample = J.buildPullRequestSummariesGraphQlQuery(
    [{ repository: "o/r", number: 1 }],
    stacks,
  );
  const match = sample.match(/pullRequest\(number: 1\) \{ (.*) \} \}\n\}$/);
  if (!match) throw new Error("summary selection");
  return match[1];
};
out += `\n/// The fields of one summary, and with stack membership, inside each aliased lookup of a batch.\npub const SUMMARY_SELECTION: &str = ${lit(selection(false))};\npub const SUMMARY_SELECTION_WITH_STACKS: &str = ${lit(selection(true))};\n`;
const target = new URL("../crates/server/src/pull_request_queries.rs", import.meta.url),
  temporary = new URL(target.href + ".tmp");
writeFileSync(temporary, out);
renameSync(temporary, target);
console.log(JSON.stringify({ bytes: out.length }));
